"""Merge src/tissue_interaction/*.py into ONE runnable file:  single_file/tissue_interaction_complete.py

    python scripts/build_single_file.py

Re-run it after every change to the package so the single file never drifts out of date.
"""
import ast, os, sys, textwrap

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "..", "src", "tissue_interaction")
OUT = os.path.join(HERE, "..", "single_file", "tissue_interaction_complete.py")
ORDER = ["tissue_library", "config", "phantom", "body_presets", "phantom_generators", "phantom_io",
         "scatterers", "interaction", "channel_data", "visualize", "ap_io", "points_io", "outputs",
         "pipeline", "cli"]
TITLES = {
    "tissue_library": "Tissue library", "config": "Configuration", "phantom": "Phantom container",
    "body_presets": "Body-region presets and probe classes", "phantom_generators": "Synthetic phantoms",
    "phantom_io": "Phantom loader (image / array input)", "scatterers": "Stage 1 - scatterer generation",
    "interaction": "Stage 2 - reflected pressure", "channel_data": "Stage 3 - channel data for Receiver BF",
    "visualize": "2-D grayscale maps and QA preview", "ap_io": "Acoustic Propagation file reader / emulator",
    "points_io": "Phantom as points / coordinates", "outputs": "Readers and writers",
    "pipeline": "High-level pipeline", "cli": "Command line interface and selftest"}


def process(name):
    src = open(os.path.join(SRC, name + ".py")).read()
    tree = ast.parse(src)
    lines = src.split("\n")
    drop, ext_imports, doc = set(), [], None
    body = tree.body
    if body and isinstance(body[0], ast.Expr) and isinstance(getattr(body[0], "value", None), ast.Constant) \
            and isinstance(body[0].value.value, str):
        doc = body[0].value.value
        drop.update(range(body[0].lineno, body[0].end_lineno + 1))
    for node in ast.walk(tree):
        if isinstance(node, ast.ImportFrom) and (node.level > 0):
            drop.update(range(node.lineno, node.end_lineno + 1))                  # any depth: relative import
    for node in body:
        if isinstance(node, (ast.Import, ast.ImportFrom)) and not (isinstance(node, ast.ImportFrom) and node.level > 0):
            if isinstance(node, ast.ImportFrom) and node.module == "__future__":
                drop.update(range(node.lineno, node.end_lineno + 1)); continue
            ext_imports.append(node)
            drop.update(range(node.lineno, node.end_lineno + 1))
    kept = [l for i, l in enumerate(lines, 1) if i not in drop]
    text = "\n".join(kept).strip("\n")
    return doc, ext_imports, text


def main():
    sections, imports = [], []
    for name in ORDER:
        doc, imps, text = process(name)
        imports.extend(imps)
        bar = "# " + "=" * 100
        head = [bar, f"# {TITLES[name]}   (module: {name}.py)", bar]
        if doc:
            head += ["#"] + [("# " + l).rstrip() for l in textwrap.dedent(doc).strip().split("\n")]
        sections.append("\n".join(head) + "\n\n" + text + "\n")
    plain, frm = {}, {}
    for node in imports:
        if isinstance(node, ast.Import):
            for a in node.names:
                plain[(a.name, a.asname)] = True
        else:
            for a in node.names:
                frm.setdefault(node.module, {})[(a.name, a.asname)] = True
    lines_ = []
    for (n, asn) in plain:
        lines_.append(f"import {n}" + (f" as {asn}" if asn else ""))
    for mod, names in frm.items():
        items = ", ".join(n + (f" as {a}" if a else "") for (n, a) in names)
        lines_.append(f"from {mod} import {items}")
    third_keys = ("numpy", "scipy", "matplotlib", "PIL", "yaml")
    std = sorted(l for l in lines_ if not any(k in l for k in third_keys))
    third = sorted(l for l in lines_ if any(k in l for k in third_keys))
    third = ["", *third]
    header = '''#!/usr/bin/env python3
"""NITK-UsoundSim - Tissue Interaction module (Subtask 04) - COMPLETE SINGLE-FILE VERSION.

Generated by scripts/build_single_file.py from the package in src/tissue_interaction/ (do not edit by hand).

What it does
    phantom (points / coordinates, image) or Acoustic Propagation forward_propagation() file
      -> tissue-aware scatterers -> reflected pressure of every scatterer
      -> echoes at the receive elements (channel data) for the Receiver Beamforming team
      -> 2-D grayscale maps

Use as a script
    python tissue_interaction_complete.py selftest
    python tissue_interaction_complete.py demo --body-part thyroid --out outputs
    python tissue_interaction_complete.py from-ap --forward forward_propagation_output.npz --out outputs/echo
    python tissue_interaction_complete.py run --points points.csv --body-part abdomen --out outputs/run
    python tissue_interaction_complete.py --help

Use as a library (same folder / Colab cell)
    import tissue_interaction_complete as ti
    res = ti.run_from_ap("forward_propagation_output.npz")      # res.channel_rf -> Receiver Beamforming

Requires: numpy, scipy, matplotlib, pillow, pyyaml
"""
from __future__ import annotations

'''
    body = header + "\n".join(std + third) + '\n\n__version__ = "0.2.0"\n\n\n' + "\n\n".join(sections)
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, "w").write(body)
    print("wrote", os.path.abspath(OUT), f"({body.count(chr(10))} lines)")


if __name__ == "__main__":
    main()
