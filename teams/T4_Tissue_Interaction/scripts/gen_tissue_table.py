import os
from tissue_interaction.tissue_library import markdown_table
from tissue_interaction.body_presets import BODY_PRESETS, PROBE_CLASSES
out = os.path.join(os.path.dirname(__file__), "..", "docs", "TISSUE_TABLE.md")
lines = ["# Built-in tissue library\n", "Auto-generated by `scripts/gen_tissue_table.py`. Values are textbook "
         "mid-range starting points - tune them against Philips images / reference tables.\n", markdown_table(), "\n",
         "# Body-region presets\n", "| body part | probe class | f0 (MHz) | field of view (mm) | default label legend (id: tissue) |", "|---|---|---|---|---|"]
for k, b in sorted(BODY_PRESETS.items()):
    pc = PROBE_CLASSES[b.probe]
    leg = ", ".join(f"{i}: {n}" for i, n in b.legend.items())
    lines.append(f"| {k} | {pc.name} ({pc.geometry}) | {pc.f0_hz/1e6:g} | {b.width_mm:g} x {b.depth_mm:g} | {leg} |")
open(out, "w").write("\n".join(lines) + "\n")
print("wrote", out)
